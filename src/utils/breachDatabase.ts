// Leetspeak substitutions
const LEET_MAP: Record<string, string> = {
  '@': 'a',
  '4': 'a',
  '8': 'b',
  '(': 'c',
  '3': 'e',
  '6': 'g',
  '!': 'i',
  '1': 'i',
  '|': 'l',
  '0': 'o',
  '$': 's',
  '5': 's',
  '+': 't',
  '7': 't',
  '2': 'z',
  '%': 'x',
};

export function normalizeLeetspeak(input: string): string {
  let result = '';
  for (let i = 0; i < input.length; i++) {
    const char = input[i].toLowerCase();
    result += LEET_MAP[char] || char;
  }
  return result;
}

// Common keyboard spatial sequences
const KEYBOARD_ROWS = [
  '1234567890-=',
  'qwertyuiop[]\\',
  'asdfghjkl;\'',
  'zxcvbnm,./',
];

const KEYBOARD_COLUMNS = [
  '1qaz',
  '2wsx',
  '3edc',
  '4rfv',
  '5tgb',
  '6yhn',
  '7ujm',
  '8ik,',
  '9ol.',
  '0p;/',
];

export function checkKeyboardWalk(input: string): { found: boolean; pattern?: string } {
  const lower = input.toLowerCase();
  if (lower.length < 3) return { found: false };

  // Check horizontal rows forward and reverse
  for (const row of KEYBOARD_ROWS) {
    const revRow = row.split('').reverse().join('');
    for (let i = 0; i <= row.length - 3; i++) {
      const sub = row.substring(i, i + 3);
      const subRev = revRow.substring(i, i + 3);
      if (lower.includes(sub)) {
        return { found: true, pattern: `Horizontal keyboard sequence "${sub}" detected` };
      }
      if (lower.includes(subRev)) {
        return { found: true, pattern: `Reverse horizontal keyboard sequence "${subRev}" detected` };
      }
    }
  }

  // Check vertical columns
  for (const col of KEYBOARD_COLUMNS) {
    const revCol = col.split('').reverse().join('');
    for (let i = 0; i <= col.length - 3; i++) {
      const sub = col.substring(i, i + 3);
      const subRev = revCol.substring(i, i + 3);
      if (lower.includes(sub)) {
        return { found: true, pattern: `Vertical keyboard column sequence "${sub}" detected` };
      }
      if (lower.includes(subRev)) {
        return { found: true, pattern: `Reverse vertical keyboard sequence "${subRev}" detected` };
      }
    }
  }

  return { found: false };
}

export function checkSequentialRuns(input: string): { found: boolean; pattern?: string } {
  const lower = input.toLowerCase();
  if (lower.length < 3) return { found: false };

  // Alphabetical
  const alphabet = 'abcdefghijklmnopqrstuvwxyz';
  const revAlphabet = alphabet.split('').reverse().join('');

  for (let i = 0; i <= alphabet.length - 3; i++) {
    const sub = alphabet.substring(i, i + 3);
    const subRev = revAlphabet.substring(i, i + 3);
    if (lower.includes(sub)) {
      return { found: true, pattern: `Alphabetical run "${sub}" detected` };
    }
    if (lower.includes(subRev)) {
      return { found: true, pattern: `Reverse alphabetical run "${subRev}" detected` };
    }
  }

  // Numerical sequences
  const numbers = '01234567890';
  const revNumbers = numbers.split('').reverse().join('');
  for (let i = 0; i <= numbers.length - 3; i++) {
    const sub = numbers.substring(i, i + 3);
    const subRev = revNumbers.substring(i, i + 3);
    if (lower.includes(sub)) {
      return { found: true, pattern: `Sequential number run "${sub}" detected` };
    }
    if (lower.includes(subRev)) {
      return { found: true, pattern: `Reverse sequential number run "${subRev}" detected` };
    }
  }

  return { found: false };
}

export function checkRepeatedChars(input: string): { found: boolean; pattern?: string } {
  if (input.length < 3) return { found: false };

  // 3 or more identical consecutive characters (e.g., 'aaa' or '111')
  const repeatRegex = /(.)\1{2,}/;
  const match = input.match(repeatRegex);
  if (match) {
    return {
      found: true,
      pattern: `Repeated sequence "${match[0]}" (${match[0].length} repetitions of '${match[1]}')`,
    };
  }

  // Repeating 2-char blocks like 'ababab' or '121212'
  const blockRegex = /(.{2,4})\1{2,}/;
  const blockMatch = input.match(blockRegex);
  if (blockMatch) {
    return {
      found: true,
      pattern: `Repeating block pattern "${blockMatch[0]}" detected`,
    };
  }

  return { found: false };
}

export function checkDateOrYear(input: string): { found: boolean; pattern?: string } {
  // Years between 1950 and 2035
  const yearRegex = /(19[5-9]\d|20[0-3]\d)/;
  const match = input.match(yearRegex);
  if (match) {
    return { found: true, pattern: `Common calendar year "${match[0]}" found` };
  }

  // MMDDYY or DDMMYY formats
  const dateRegex = /(0[1-9]|1[0-2])(0[1-9]|[12]\d|3[01])(\d{2})/;
  const dateMatch = input.match(dateRegex);
  if (dateMatch && input.length <= 10) {
    return { found: true, pattern: `Date-like digit structure "${dateMatch[0]}" found` };
  }

  return { found: false };
}

export function checkBreachDictionary(input: string): {
  isBreached: boolean;
  rank?: number;
  count?: number;
  details?: string;
  matchedWord?: string;
} {
  const lower = input.toLowerCase().trim();
  if (!lower) return { isBreached: false };

  // Exact match
  if (breachedSet.has(lower)) {
    const data = breachedSet.get(lower)!;
    return {
      isBreached: true,
      rank: data.rank,
      count: data.count,
      matchedWord: lower,
      details: `Exact match found in global breach list (RockYou #Rank ${data.rank}, exposed in over ${data.count.toLocaleString()} known breaches).`,
    };
  }

  // Normalized leetspeak match
  const normalized = normalizeLeetspeak(lower);
  if (normalized !== lower && breachedSet.has(normalized)) {
    const data = breachedSet.get(normalized)!;
    return {
      isBreached: true,
      rank: data.rank,
      count: data.count,
      matchedWord: normalized,
      details: `Leetspeak obfuscation detected! Decodes to "${normalized}", a high-frequency breached password (#Rank ${data.rank}).`,
    };
  }

  // Substring match for roots >= 4 chars
  for (const entry of TOP_BREACHED_PASSWORDS) {
    if (entry.password.length >= 4 && lower.includes(entry.password)) {
      return {
        isBreached: true,
        rank: entry.rank,
        count: entry.count,
        matchedWord: entry.password,
        details: `Contains common breached root keyword "${entry.password}" (breached rank #${entry.rank}). Attackers use dictionary masks to crack these in seconds.`,
      };
    }
  }

  return { isBreached: false };
}
